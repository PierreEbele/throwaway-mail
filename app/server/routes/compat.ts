import type { Context, Hono } from "hono";
import { cors } from "hono/cors";
import type { AppEnv } from "../context.js";
import { resolveApiKey } from "../auth/tokens.js";
import { RateLimiter } from "../auth/ratelimit.js";
import { HttpError } from "../lib/errors.js";
import { createAddress } from "../services/addresses.js";
import { addressOut } from "../services/serialize.js";

/**
 * Minimal SimpleLogin- and addy.io-compatible endpoints, so the Bitwarden/Vaultwarden username generator
 * ("Forwarded email alias", self-hosted server URL) can create addresses here. Same API keys as /v1.
 *  - SimpleLogin: POST /api/alias/random/new?hostname=<site>  header `Authentication: <key>`  body { note }  → { alias }
 *  - addy.io:     POST /api/v1/aliases  `Authorization: Bearer <key>`  body { domain, description }  → { data: { email } }
 */

const HOST_RE = /\b((?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63})\b/i;

/** Bitwarden sends "Website: example.com. Generated by Bitwarden." (localised); keep the host name. */
export function siteFromText(text: string | undefined): string | null {
  const m = text ? HOST_RE.exec(text) : null;
  return m ? m[1]!.toLowerCase() : null;
}

function cleanHost(raw: string | undefined): string | null {
  const v = (raw ?? "").trim().toLowerCase();
  if (!v) return null;
  try {
    return new URL(/^https?:\/\//.test(v) ? v : `https://${v}`).hostname || null;
  } catch {
    return null;
  }
}

function caller(c: Context<AppEnv>) {
  const raw = c.req.header("authentication") ?? /^Bearer\s+(\S+)$/i.exec(c.req.header("authorization") ?? "")?.[1];
  const r = raw ? resolveApiKey(c.get("deps"), raw.trim()) : null;
  if (!r) throw new HttpError(401, "invalid_api_key", "Invalid or revoked API key");
  return r;
}

async function jsonBody(c: Context<AppEnv>): Promise<Record<string, unknown>> {
  const b = await c.req.json().catch(() => ({}));
  return b && typeof b === "object" ? (b as Record<string, unknown>) : {};
}

const str = (v: unknown, max: number) => (typeof v === "string" ? v.trim().slice(0, max) : undefined);

export function registerCompat(app: Hono<AppEnv>, limiter: RateLimiter) {
  // Token auth only (no cookies), so any origin may call it: the Bitwarden web vault and desktop app need CORS.
  app.use(
    "/api/*",
    cors({
      origin: "*",
      allowMethods: ["POST", "OPTIONS"],
      allowHeaders: ["Authentication", "Authorization", "Content-Type"],
      maxAge: 86400,
    }),
  );
  app.use("/api/*", async (c, next) => {
    if (c.req.method === "OPTIONS") return next();
    const r = limiter.hit(`compat:${c.req.header("authentication") || c.req.header("authorization") || "anon"}`);
    if (!r.ok) throw new HttpError(429, "rate_limited", `Too many requests, retry in ${r.retryAfter}s`);
    await next();
  });

  app.post("/api/alias/random/new", async (c) => {
    const { user } = caller(c);
    const body = await jsonBody(c);
    const note = str(body.note, 120);
    const site = cleanHost(c.req.query("hostname")) ?? siteFromText(note);
    const { a, domain } = createAddress(c.get("deps"), user, {
      site_name: site ?? "Bitwarden",
      site_url: site ? `https://${site}` : null,
      label: note || "Bitwarden",
    });
    const o = addressOut(a, domain);
    return c.json(
      { id: a.id, alias: o.email, email: o.email, creation_timestamp: Math.floor(a.createdAt / 1000), enabled: true, note: a.label },
      201,
    );
  });

  app.post("/api/v1/aliases", async (c) => {
    const { user } = caller(c);
    const body = await jsonBody(c);
    const description = str(body.description, 200);
    const site = siteFromText(description);
    const { a, domain } = createAddress(c.get("deps"), user, {
      domain: str(body.domain, 253)?.toLowerCase() || undefined,
      site_name: site ?? "Bitwarden",
      site_url: site ? `https://${site}` : null,
      label: description || "Bitwarden",
    });
    const o = addressOut(a, domain);
    return c.json(
      {
        data: {
          id: a.id,
          email: o.email,
          local_part: a.localPart,
          domain,
          description: a.label,
          active: true,
          created_at: new Date(a.createdAt).toISOString(),
        },
      },
      201,
    );
  });

  app.all("/api/*", (c) => c.json({ error: { code: "not_found", message: "Route not found" } }, 404));
}
