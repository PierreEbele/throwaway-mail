import { describe, expect, it } from "vitest";
import { Client, addDomain, ingest, makeTestApp, setupAdmin, simpleEml, type TestApp } from "../helpers.js";

async function setup() {
  const t = makeTestApp();
  const admin = await setupAdmin(t);
  await addDomain(admin, "mail.example.test");
  const a = (await admin.post("/v1/addresses", { site_name: "Allowed" })).json;
  const b = (await admin.post("/v1/addresses", { site_name: "Other" })).json;
  return { t, admin, a, b };
}

async function keyClient(t: TestApp, admin: Client, body: Record<string, unknown>) {
  const r = await admin.post("/v1/keys", { name: "scoped", ...body });
  expect(r.status).toBe(201);
  const c = new Client(t);
  c.bearer = r.json.key;
  return { c, apiKey: r.json.api_key, secret: r.json.key as string };
}

const compat = (t: TestApp, key: string) =>
  t.app.request("/api/alias/random/new", {
    method: "POST",
    headers: { "content-type": "application/json", authentication: key },
    body: JSON.stringify({ note: "Generated by Bitwarden." }),
  });

describe("API key scopes", () => {
  it("existing-style keys are full and unrestricted", async () => {
    const { t, admin, a } = await setup();
    const { c, apiKey, secret } = await keyClient(t, admin, {});
    expect(apiKey.scope).toBe("full");
    expect(apiKey.address_ids).toBeNull();
    expect(apiKey.expires_at).toBeNull();
    expect((await c.get("/v1/addresses")).json.addresses).toHaveLength(2);
    expect((await c.patch(`/v1/addresses/${a.id}`, { label: "x" })).status).toBe(200);
    expect((await compat(t, secret)).status).toBe(201);
  });

  it("read-only keys can read but every write is refused, compat API included", async () => {
    const { t, admin, a } = await setup();
    const { c, secret } = await keyClient(t, admin, { scope: "read" });
    expect((await c.get("/v1/addresses")).json.addresses).toHaveLength(2);
    expect((await c.get(`/v1/addresses/${a.id}`)).status).toBe(200);
    for (const r of [
      await c.post("/v1/addresses", { site_name: "Nope" }),
      await c.patch(`/v1/addresses/${a.id}`, { label: "x" }),
      await c.req("DELETE", `/v1/addresses/${a.id}`),
      await c.post("/v1/keys", { name: "escalate" }),
    ]) {
      expect(r.status).toBe(403);
      expect(r.json.error.code).toBe("insufficient_scope");
    }
    expect((await compat(t, secret)).status).toBe(403);
  });

  it("address-restricted keys only see their addresses and messages", async () => {
    const { t, admin, a, b } = await setup();
    await ingest(t, a.email, simpleEml({ text: "Your code is 111111" }));
    await ingest(t, b.email, simpleEml({ text: "Your code is 222222" }));
    const { c, secret } = await keyClient(t, admin, { address_ids: [a.id] });

    const list = (await c.get("/v1/addresses?status=all")).json.addresses;
    expect(list.map((x: { id: string }) => x.id)).toEqual([a.id]);
    expect((await c.get(`/v1/addresses/${a.id}`)).status).toBe(200);
    expect((await c.get(`/v1/addresses/${a.id}/code`)).json.code).toBe("111111");
    expect((await c.patch(`/v1/addresses/${a.id}`, { label: "ok" })).status).toBe(200);
    expect((await c.get(`/v1/addresses/${b.id}`)).status).toBe(404);
    expect((await c.get(`/v1/addresses/${b.id}/code`)).status).toBe(404);

    const msgA = (await admin.get(`/v1/addresses/${a.id}/messages`)).json.messages[0].id;
    const msgB = (await admin.get(`/v1/addresses/${b.id}/messages`)).json.messages[0].id;
    expect((await c.get(`/v1/messages/${msgA}`)).status).toBe(200);
    expect((await c.get(`/v1/messages/${msgB}`)).status).toBe(404);
    expect((await c.req("DELETE", `/v1/messages/${msgB}`)).status).toBe(404);

    // Account-wide routes, creation and the compat API are closed.
    for (const path of ["/v1/export", "/v1/categories", "/v1/keys", "/v1/domains", "/v1/review"]) {
      expect((await c.get(path)).status, path).toBe(403);
    }
    expect((await c.post("/v1/addresses", { site_name: "Nope" })).status).toBe(403);
    expect((await c.post("/v1/addresses/bulk", { action: "pause", ids: [b.id] })).status).toBe(403);
    // Replacing an in-scope address would create a new one: refused too, and nothing changes.
    expect((await c.post(`/v1/addresses/${a.id}/replace`, {})).status).toBe(403);
    expect((await c.post(`/v1/addresses/${a.id}/rejected`, { replace: true })).status).toBe(403);
    expect((await admin.get("/v1/addresses?status=all")).json.addresses).toHaveLength(2);
    expect((await admin.get(`/v1/addresses/${a.id}`)).json.address.status).toBe("active");
    expect((await compat(t, secret)).status).toBe(403);
  });

  it("address-restricted keys only receive SSE events of their addresses", async () => {
    const { t, admin, a, b } = await setup();
    const { secret } = await keyClient(t, admin, { address_ids: [a.id] });
    const ac = new AbortController();
    const res = await t.app.request("/v1/events", { headers: { authorization: `Bearer ${secret}` }, signal: ac.signal });
    expect(res.status).toBe(200);
    const reader = res.body!.getReader();
    const dec = new TextDecoder();
    let text = "";
    let pending: ReturnType<typeof reader.read> | null = null;
    const readFor = async (ms: number) => {
      const end = Date.now() + ms;
      while (Date.now() < end) {
        pending ??= reader.read();
        const r = await Promise.race([pending, new Promise<null>((ok) => setTimeout(() => ok(null), end - Date.now()))]);
        if (!r) break;
        pending = null;
        if (r.done) break;
        text += dec.decode(r.value);
      }
    };
    await readFor(100);
    expect(text).toContain("event: ready");
    await ingest(t, b.email, simpleEml({ text: "Your code is 222222" }));
    await ingest(t, a.email, simpleEml({ text: "Your code is 111111" }));
    await readFor(300);
    ac.abort();
    await reader.cancel().catch(() => {});
    expect(text).toContain(a.id);
    expect(text).not.toContain(b.id);
  });

  it("rejects unknown addresses at creation and expires keys", async () => {
    const { t, admin, a } = await setup();
    expect((await admin.post("/v1/keys", { name: "x", address_ids: ["adr_nope"] })).status).toBe(400);
    expect((await admin.post("/v1/keys", { name: "x", expires_at: 1000 })).status).toBe(400);
    const { c, apiKey } = await keyClient(t, admin, { expires_in_days: 1 });
    expect(apiKey.expires_at).toBeGreaterThan(Date.now());
    expect((await c.get(`/v1/addresses/${a.id}`)).status).toBe(200);
    const realNow = t.deps.now;
    t.deps.now = () => realNow() + 2 * 86400_000;
    const r = await c.get(`/v1/addresses/${a.id}`);
    t.deps.now = realNow;
    expect(r.status).toBe(401);
  });
});
