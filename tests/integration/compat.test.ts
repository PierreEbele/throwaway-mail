import { describe, expect, it } from "vitest";
import { siteFromText } from "../../app/server/routes/compat.js";
import { addDomain, makeTestApp, setupAdmin } from "../helpers.js";

async function setup() {
  const t = makeTestApp();
  const admin = await setupAdmin(t);
  await addDomain(admin, "mail.example.test");
  await addDomain(admin, "other.example.test");
  const key = (await admin.post("/v1/keys", { name: "bitwarden" })).json.key as string;
  const call = (path: string, headers: Record<string, string>, body: unknown) =>
    t.app.request(path, { method: "POST", headers: { "content-type": "application/json", ...headers }, body: JSON.stringify(body) });
  return { t, admin, key, call };
}

describe("Bitwarden alias-service compatibility", () => {
  it("SimpleLogin: creates an address from hostname + note (Authentication header)", async () => {
    const { admin, key, call } = await setup();
    const res = await call("/api/alias/random/new?hostname=shop.example.org", { authentication: key }, { note: "Website: shop.example.org. Generated by Bitwarden." });
    expect(res.status).toBe(201);
    const json = (await res.json()) as any;
    expect(json.alias).toMatch(/@mail\.example\.test$/);
    const list = (await admin.get("/v1/addresses")).json.addresses;
    const a = list.find((x: any) => x.email === json.alias);
    expect(a.site_name).toBe("shop.example.org");
    expect(a.site_url).toBe("https://shop.example.org");
    expect(a.label).toBe("Website: shop.example.org. Generated by Bitwarden.");
  });

  it("addy.io: uses the requested domain and the site from the description (Bearer)", async () => {
    const { admin, key, call } = await setup();
    const res = await call("/api/v1/aliases", { authorization: `Bearer ${key}` }, { domain: "other.example.test", description: "Site web : forum.example.net. Généré par Bitwarden." });
    expect(res.status).toBe(201);
    const json = (await res.json()) as any;
    expect(json.data.email).toMatch(/@other\.example\.test$/);
    const a = (await admin.get(`/v1/addresses/${json.data.id}`)).json.address;
    expect(a.site_name).toBe("forum.example.net");
  });

  it("works without a website and rejects unknown domains and bad keys", async () => {
    const { key, call } = await setup();
    const plain = await call("/api/alias/random/new", { authentication: key }, { note: "Generated by Bitwarden." });
    expect(plain.status).toBe(201);
    expect(((await call("/api/v1/aliases", { authorization: `Bearer ${key}` }, { domain: "nope.example" })) as Response).status).toBe(400);
    expect((await call("/api/alias/random/new", { authentication: "tm_wrong" }, {})).status).toBe(401);
    expect((await call("/api/alias/random/new", {}, {})).status).toBe(401);
  });

  it("answers CORS preflight for the Bitwarden web vault, without cookies", async () => {
    const { t } = await setup();
    const res = await t.app.request("/api/alias/random/new", {
      method: "OPTIONS",
      headers: { origin: "https://vault.example.org", "access-control-request-method": "POST", "access-control-request-headers": "authentication,content-type" },
    });
    expect(res.status).toBeLessThan(300);
    expect(res.headers.get("access-control-allow-origin")).toBe("*");
    expect(res.headers.get("access-control-allow-headers")?.toLowerCase()).toContain("authentication");
    expect(res.headers.get("access-control-allow-credentials")).toBeNull();
  });

  it("extracts the site from localised Bitwarden notes", () => {
    expect(siteFromText("Website: accounts.example.com. Generated by Bitwarden.")).toBe("accounts.example.com");
    expect(siteFromText("Site web : Example.FR. Généré par Bitwarden.")).toBe("example.fr");
    expect(siteFromText("Generated by Bitwarden.")).toBeNull();
  });
});
